export class I18nManager {
  constructor() {
    this.lang = (typeof localStorage !== 'undefined' ? localStorage.getItem('dbtcg_lang') : null) || 'pt';
  }

  setLanguage(lang) {
    if (lang !== 'pt' && lang !== 'en') return;
    this.lang = lang;
    localStorage.setItem('dbtcg_lang', lang);
  }

  t(key) {
    const dict = TRANSLATIONS[this.lang] || TRANSLATIONS.pt;
    return dict[key] || key;
  }
}

export const i18n = new I18nManager();
